-- drop: cat_t
CREATE TABLE cat_t (id int PRIMARY KEY, name text NOT NULL DEFAULT 1::text, v numeric(10,2));
CREATE INDEX cat_t_name ON cat_t(name);
CREATE FUNCTION cat_f(a int, b text DEFAULT $f$x$f$) RETURNS text LANGUAGE sql AS $f$ SELECT b $f$;
CREATE FUNCTION cat_o(text) RETURNS text AS $f$ SELECT lower($1) $f$ LANGUAGE sql IMMUTABLE;
CREATE FUNCTION cat_o(character varying) RETURNS text AS $f$ SELECT cat_o($1::text) $f$ LANGUAGE sql IMMUTABLE;
CREATE TYPE cat_e AS ENUM ($f$a$f$, $f$b$f$);
