func TestSQLSequences(t *testing.T) {
	e := newEngine(t)
	s := NewSession(e)
	one := func(q string) Datum {
		t.Helper()
		r := run(t, s, q)
		if len(r.Rows) != 1 {
			t.Fatalf("%s: %s", q, render(r))
		}
		return r.Rows[0][0]
	}
	wantErr := func(q, c string) {
		t.Helper()
		if _, err := tryRun(s, q); code(err) != c {
			t.Fatalf("%s: got %v, want %s", q, err, c)
		}
	}
	run(t, s, `CREATE SEQUENCE s1 START 10 INCREMENT BY 5`)
	if r := run(t, s, `SELECT nextval('s1'), nextval('public.s1')`); r.Rows[0][0].I != 10 || r.Rows[0][1].I != 15 {
		t.Fatalf("nextval: %s", render(r))
	}
	if one(`SELECT currval('s1')`).I != 15 || one(`SELECT lastval()`).I != 15 {
		t.Fatal("currval/lastval")
	}
	if _, err := tryRun(NewSession(e), `SELECT currval('s1')`); code(err) != "55000" {
		t.Fatalf("currval in a new session: %v", err)
	}
	one(`SELECT setval('s1', 100)`)
	if one(`SELECT nextval('s1'::regclass)`).I != 105 {
		t.Fatal("setval called")
	}
	one(`SELECT setval('s1', 7, false)`)
	if one(`SELECT nextval('s1')`).I != 7 {
		t.Fatal("setval not called")
	}
	if r := run(t, s, `SELECT last_value, is_called FROM s1`); r.Rows[0][0].I != 7 || !r.Rows[0][1].Bool() {
		t.Fatalf("select from sequence: %s", render(r))
	}
	run(t, s, `ALTER SEQUENCE s1 RESTART WITH 1`)
	if one(`SELECT nextval('s1')`).I != 1 {
		t.Fatal("restart")
	}
	wantErr(`CREATE SEQUENCE s1`, codeDuplicateTable)
	if r := run(t, s, `CREATE SEQUENCE IF NOT EXISTS s1`); r.Notice == "" {
		t.Fatal("if not exists notice")
	}
	run(t, s, `CREATE SEQUENCE sm AS smallint MAXVALUE 2`)
	one(`SELECT nextval('sm')`)
	one(`SELECT nextval('sm')`)
	wantErr(`SELECT nextval('sm')`, "2200H")
	wantErr(`CREATE SEQUENCE bad AS smallint MAXVALUE 40000`, "22023")
	run(t, s, `DROP SEQUENCE s1, sm`)
	wantErr(`SELECT nextval('s1')`, codeUndefinedTable)

	// SERIAL and DEFAULT
	run(t, s, `CREATE TABLE items (id serial PRIMARY KEY, name text NOT NULL DEFAULT 'x', qty bigint DEFAULT 0 NOT NULL, created timestamp DEFAULT now())`)
	run(t, s, `INSERT INTO items (name) VALUES ('a')`)
	run(t, s, `CREATE TABLE docs (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), v text)`)
	run(t, s, `INSERT INTO docs (v) VALUES ('a'), ('b')`)
	if r := run(t, s, `SELECT count(DISTINCT id), min(length(id)) FROM docs`); r.Rows[0][0].I != 2 || r.Rows[0][1].I != 36 {
		t.Fatalf("gen_random_uuid default: %s", render(r))
	}
	run(t, s, `INSERT INTO items DEFAULT VALUES`)
	if one(`INSERT INTO items VALUES (DEFAULT, 'c', DEFAULT, DEFAULT) RETURNING id`).I != 3 {
		t.Fatal("RETURNING serial id")
	}
	run(t, s, `UPDATE items SET qty = 9 WHERE id = 3`)
	run(t, s, `UPDATE items SET qty = DEFAULT WHERE id = 3`)
	r := run(t, s, `SELECT id, name, qty, created IS NOT NULL FROM items ORDER BY id`)
	if got := render(r); !strings.Contains(got, "1") || len(r.Rows) != 3 || r.Rows[1][1].S != "x" || r.Rows[2][2].I != 0 || !r.Rows[0][3].Bool() {
		t.Fatalf("defaults: %s", got)
	}
	r = run(t, s, `SELECT data_type, max_value, last_value FROM pg_sequences WHERE sequencename = 'items_id_seq'`)
	if len(r.Rows) != 1 || r.Rows[0][0].S != "integer" || r.Rows[0][1].I != 2147483647 || r.Rows[0][2].I != 3 {
		t.Fatalf("pg_sequences: %s", render(r))
	}
	wantErr(`DROP SEQUENCE items_id_seq`, "2BP01")
	wantErr(`CREATE TABLE d (id bigint PRIMARY KEY, v bigint DEFAULT id)`, codeFeature)
	wantErr(`CREATE TABLE d (id serial PRIMARY KEY DEFAULT 1)`, codeSyntax)

	// IDENTITY
	run(t, s, `CREATE TABLE ev (id bigint GENERATED ALWAYS AS IDENTITY (START WITH 100) PRIMARY KEY, v text)`)
	if one(`INSERT INTO ev (v) VALUES ('a') RETURNING id`).I != 100 {
		t.Fatal("identity start")
	}
	wantErr(`INSERT INTO ev (id, v) VALUES (5, 'b')`, "428C9")
	run(t, s, `INSERT INTO ev (id, v) OVERRIDING SYSTEM VALUE VALUES (5, 'b')`)
	wantErr(`UPDATE ev SET id = 7 WHERE id = 5`, "428C9")
	run(t, s, `TRUNCATE ev RESTART IDENTITY`)
	if one(`INSERT INTO ev (v) VALUES ('c') RETURNING id`).I != 100 {
		t.Fatal("TRUNCATE RESTART IDENTITY")
	}
	run(t, s, `CREATE TABLE bd (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text)`)
	run(t, s, `INSERT INTO bd (id, v) VALUES (50, 'x')`)
	if one(`INSERT INTO bd (id, v) OVERRIDING USER VALUE VALUES (60, 'y') RETURNING id`).I != 1 {
		t.Fatal("OVERRIDING USER VALUE")
	}

	// the sequences go with their tables; restarts keep the defaults
	run(t, s, `DROP TABLE items`)
	wantErr(`SELECT nextval('items_id_seq')`, codeUndefinedTable)
	if r := run(t, s, `SELECT sequencename FROM pg_sequences ORDER BY 1`); len(r.Rows) != 2 {
		t.Fatalf("sequences after drop: %s", render(r))
	}
	if r := run(t, s, `SELECT count(*) FROM pg_publication_tables`); r.Rows[0][0].I != 0 {
		t.Fatal("system table visible")
	}
}

func TestSQLCheck(t *testing.T) {
	s := NewSession(newEngine(t))
	run(t, s, `CREATE TABLE prod (id bigint PRIMARY KEY, price float CHECK (price > 0), qty bigint,
		CONSTRAINT qty_ok CHECK (qty >= 0 AND qty < 1000), CHECK (price < 1e6))`)
	run(t, s, `INSERT INTO prod VALUES (1, 5, 1), (4, NULL, NULL)`)
	for q, name := range map[string]string{
		`INSERT INTO prod VALUES (2, -1, 1)`:                                          "prod_price_check",
		`INSERT INTO prod VALUES (3, 5, 5000)`:                                        "qty_ok",
		`INSERT INTO prod VALUES (3, 2e6, 1)`:                                         "prod_check",
		`UPDATE prod SET qty = -1 WHERE id = 1`:                                       "qty_ok",
		`INSERT INTO prod VALUES (1, 5, 1) ON CONFLICT (id) DO UPDATE SET price = -5`: "prod_price_check",
	} {
		_, err := tryRun(s, q)
		if code(err) != "23514" || !strings.Contains(err.Error(), name) {
			t.Fatalf("%s: %v, want 23514 on %s", q, err, name)
		}
	}
	if _, err := tryRun(s, `CREATE TABLE x (id bigint PRIMARY KEY CHECK (nope > 0))`); code(err) != codeUndefinedColumn {
		t.Fatalf("check on a missing column: %v", err)
	}
	if r := run(t, s, `SELECT count(*) FROM prod`); r.Rows[0][0].I != 2 {
		t.Fatalf("rows: %s", render(r))
	}
}
