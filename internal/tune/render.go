package tune

import (
	"fmt"
	"runtime"
	"strings"
	"time"
)

// Facts is everything the settings are derived from.
type Facts struct {
	Dir          string
	CPUs         float64
	Memory       int64
	Groups       bool
	GroupsReason string
	Disk         Disk
	Speed        *DiskSpeed // nil when the disk was not measured
}

// Gather detects the machine; with budget > 0 it also benchmarks the disk
// under dir.
func Gather(dir string, budget time.Duration) (Facts, error) {
	f := Facts{Dir: dir, CPUs: CPUs(), Memory: Memory(), Disk: DiskOf(dir)}
	f.Groups, f.GroupsReason = CPUGroupsPossible()
	if budget > 0 {
		s, err := MeasureDisk(dir, budget)
		if err != nil {
			return f, fmt.Errorf("disk benchmark: %w", err)
		}
		f.Speed = &s
	}
	return f, nil
}

// Render writes a staskd.conf for f: every value with the fact it comes
// from.
func Render(f Facts) string {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	mb := func(v int64) int64 { return v >> 20 }
	cpus := max(1, int(f.CPUs+0.999))
	p("# staskd.conf generated by stasktune on %s (%s/%s)", time.Now().Format(time.RFC3339), runtime.GOOS, runtime.GOARCH)
	p("# Re-run stasktune after moving to other hardware or changing container")
	p("# limits. Values can be edited; flags on the command line win.")
	p("#")
	p("# detected: %.2f CPUs usable (affinity and cgroup cpu.max), %d MiB memory", f.CPUs, mb(f.Memory))
	p("#           (RAM and cgroup memory.max), disk %s (%s, %s), %d of %d GiB free",
		orUnknown(f.Disk.Device), orUnknown(f.Disk.FS), map[bool]string{true: "rotational", false: "solid state"}[f.Disk.Rotational],
		f.Disk.FreeBytes>>30, f.Disk.SizeBytes>>30)
	if s := f.Speed; s != nil {
		p("# measured: sequential write %.0f MB/s; fdatasync after a 4 KiB write:", s.SeqWriteMBps)
		p("#           preallocated space p50 %v p99 %v (%d ops), zero-filled p50 %v p99 %v (%d ops)",
			s.SyncFreshP50.Round(time.Microsecond), s.SyncFreshP99.Round(time.Microsecond), s.SyncFreshOps,
			s.SyncZeroedP50.Round(time.Microsecond), s.SyncZeroedP99.Round(time.Microsecond), s.SyncZeroedOps)
	} else {
		p("# disk not measured (-seconds 0): disk settings are defaults")
	}
	if f.Disk.Rotational {
		p("# WARNING: rotational disk. Committed values are read back from the log by")
		p("# random reads; expect much higher read latency than on SSD/NVMe.")
	}
	p("")
	p("dir = %s", f.Dir)
	p("")
	p("# ---- CPU: use all %d ----", cpus)
	p("# one aggregate worker per usable CPU; no heavy lane (it raises GOMAXPROCS")
	p("# above the CPUs, and GC mark workers then crowd out statements)")
	p("heavy-workers = 0")
	p("scan-workers = %d", cpus)
	p("# GOMAXPROCS: 0 = derived from the usable CPUs")
	p("procs = 0")
	p("# CPU groups weigh foreground statements against background work;")
	if f.Groups {
		p("# available where stasktune ran")
	} else {
		p("# NOT available where stasktune ran (%s).", f.GroupsReason)
		p("# staskd falls back to nice values by itself; to have the groups, run")
		p("# it under systemd with Delegate=yes, or in a container with a private,")
		p("# writable cgroup namespace")
	}
	p("cpu-groups = true")
	p("fg-weight = 1000")
	p("heavy-weight = 50")
	p("heavy-nice = 10")
	p("runnable-threshold = 4")
	p("# CPUs background work may keep while the CPU is overloaded (0 = no cap)")
	p("heavy-cap = 0")
	p("scan-min-helpers = 1")
	p("")
	p("# ---- memory: %d MiB usable ----", mb(f.Memory))
	p("# Go heap soft limit: half; the rest is page cache for reading values")
	p("# from the log (memory mapped) and room for checkpoints")
	p("mem-limit-mb = %d", max(256, mb(f.Memory)/2))
	p("go-gc = 400")
	p("")
	p("# ---- commit log ----")
	seg := int64(256)
	switch free := f.Disk.FreeBytes; {
	case free > 0 && free < 8<<30:
		seg = 64
	case free > 0 && free < 64<<30:
		seg = 128
	}
	p("# segment size by free space (%d GiB)", f.Disk.FreeBytes>>30)
	p("segment-mb = %d", seg)
	if s := f.Speed; s != nil {
		gain := float64(s.SyncFreshP50) / float64(max(1, s.SyncZeroedP50))
		zeroRate := max(16, int64(s.SeqWriteMBps*0.25))
		if gain >= 1.3 {
			p("# fdatasync into zero-filled space is %.1fx faster than into", gain)
			p("# preallocated space: write zeros ahead of the log, at a quarter of")
			p("# the disk's sequential bandwidth")
			p("prezero = true")
		} else {
			p("# fdatasync into zero-filled space is only %.2fx faster: writing", gain)
			p("# the log twice is not worth it")
			p("prezero = false")
		}
		p("zero-rate-mb = %d", zeroRate)
		p("# commit batches wait at most one fdatasync for more clients")
		w := min(time.Millisecond, s.SyncZeroedP50)
		if gain < 1.3 {
			w = min(time.Millisecond, s.SyncFreshP50)
		}
		p("commit-wait = %v", w.Round(10*time.Microsecond))
		p("")
		p("# ---- log reclamation ----")
		p("# relocation writes capped at a fifth of the sequential bandwidth")
		p("gc-rate-mb = %d", max(16, int64(s.SeqWriteMBps*0.2)))
	} else {
		p("prezero = true")
		p("zero-rate-mb = 150")
		p("commit-wait = 1ms")
		p("")
		p("# ---- log reclamation ----")
		p("gc-rate-mb = 64")
	}
	p("gc = true")
	p("history-retention = 1h")
	return b.String()
}

func orUnknown(s string) string {
	if s == "" {
		return "unknown"
	}
	return s
}
