-- ### 05_transactions/two-phase
SET search_path = s05;
BEGIN;
INSERT INTO acct VALUES (40, 'twopc', 1);
PREPARE TRANSACTION 'suite_tx1';
SELECT count(*) FROM acct WHERE id = 40;
SELECT gid::text FROM pg_prepared_xacts WHERE gid = 'suite_tx1';
COMMIT PREPARED 'suite_tx1';
SELECT count(*) FROM acct WHERE id = 40;
BEGIN;
INSERT INTO acct VALUES (41, 'twopc2', 1);
PREPARE TRANSACTION 'suite_tx2';
ROLLBACK PREPARED 'suite_tx2';
SELECT count(*) FROM acct WHERE id = 41;
COMMIT PREPARED 'suite_nosuch';
ROLLBACK PREPARED 'suite_nosuch';
PREPARE TRANSACTION 'not_in_tx';
BEGIN;
PREPARE TRANSACTION 'suite_tx3';
ROLLBACK PREPARED 'suite_tx3';
DELETE FROM acct WHERE id >= 40;

