func TestMatView(t *testing.T) {
	e := newEngine(t)
	s := NewSession(e)
	run(t, s, `CREATE TABLE sales (id INTEGER PRIMARY KEY, carrier TEXT, amt NUMERIC(12,2))`)
	run(t, s, `INSERT INTO sales VALUES (1,'v',10.00),(2,'v',5.50),(3,'m',1.00)`)
	r := run(t, s, `CREATE MATERIALIZED VIEW mv AS SELECT carrier, sum(amt) AS total, count(*) AS n FROM sales GROUP BY carrier`)
	if r.Tag != "SELECT 2" {
		t.Fatalf("tag %q", r.Tag)
	}
	wantRows(t, s, `SELECT carrier, total, n FROM mv ORDER BY carrier`, "m|1.00|1", "v|15.50|2")
	// stale until refreshed
	run(t, s, `INSERT INTO sales VALUES (4,'m',9.00)`)
	wantRows(t, s, `SELECT total FROM mv WHERE carrier = 'm'`, "1.00")
	run(t, s, `REFRESH MATERIALIZED VIEW mv`)
	wantRows(t, s, `SELECT total FROM mv WHERE carrier = 'm'`, "10.00")
	// writes are refused
	for _, q := range []string{`INSERT INTO mv VALUES ('x', 1, 1)`, `UPDATE mv SET n = 0`, `DELETE FROM mv`} {
		if _, err := tryRun(s, q); code(err) != codeWrongObject {
			t.Fatalf("%s: %v", q, err)
		}
	}
	// catalogs
	wantRows(t, s, `SELECT relkind FROM pg_class WHERE relname = 'mv'`, "m")
	wantRows(t, s, `SELECT matviewname, ispopulated FROM pg_matviews`, "mv|t")
	wantRows(t, s, `SELECT count(*) FROM pg_tables WHERE tablename = 'mv'`, "0")
	// concurrently needs a unique index
	if _, err := tryRun(s, `REFRESH MATERIALIZED VIEW CONCURRENTLY mv`); code(err) != codeNotPopulated {
		t.Fatalf("concurrently without index: %v", err)
	}
	run(t, s, `CREATE UNIQUE INDEX mv_carrier ON mv (carrier)`)
	run(t, s, `DELETE FROM sales WHERE id = 3`)
	run(t, s, `REFRESH MATERIALIZED VIEW CONCURRENTLY mv`)
	wantRows(t, s, `SELECT carrier, total FROM mv ORDER BY carrier`, "m|9.00", "v|15.50")
	// WITH NO DATA
	run(t, s, `CREATE MATERIALIZED VIEW mv2 AS SELECT id FROM sales WITH NO DATA`)
	if _, err := tryRun(s, `SELECT * FROM mv2`); code(err) != codeNotPopulated {
		t.Fatalf("unpopulated: %v", err)
	}
	wantRows(t, s, `SELECT ispopulated FROM pg_matviews WHERE matviewname = 'mv2'`, "f")
	run(t, s, `REFRESH MATERIALIZED VIEW mv2`)
	wantRows(t, s, `SELECT count(*) FROM mv2`, "3")
	run(t, s, `REFRESH MATERIALIZED VIEW mv2 WITH NO DATA`)
	if _, err := tryRun(s, `SELECT * FROM mv2`); code(err) != codeNotPopulated {
		t.Fatalf("unpopulated again: %v", err)
	}
	// drop
	run(t, s, `DROP MATERIALIZED VIEW mv2`)
	if _, err := tryRun(s, `SELECT * FROM mv2`); code(err) != codeUndefinedTable {
		t.Fatalf("dropped: %v", err)
	}
	run(t, s, `DROP MATERIALIZED VIEW IF EXISTS mv2`)
	if _, err := tryRun(s, `DROP MATERIALIZED VIEW mv2`); code(err) != codeUndefinedTable {
		t.Fatalf("drop missing: %v", err)
	}
	if _, err := tryRun(s, `DROP MATERIALIZED VIEW sales`); code(err) != codeWrongObject {
		t.Fatalf("drop a table as a matview: %v", err)
	}
}

func TestTruncateCascadeAndInsertForms(t *testing.T) {
	e := newEngine(t)
	s := NewSession(e)
	run(t, s, `CREATE TABLE p (id INTEGER PRIMARY KEY)`)
	run(t, s, `CREATE TABLE c (id SERIAL PRIMARY KEY, pid INTEGER REFERENCES p(id))`)
	run(t, s, `CREATE TABLE g (id SERIAL PRIMARY KEY, cid INTEGER REFERENCES c(id))`)
	run(t, s, `INSERT INTO p VALUES (1)`)
	run(t, s, `INSERT INTO c (pid) VALUES (1), (1)`)
	run(t, s, `INSERT INTO g (cid) VALUES (1)`)
	if _, err := tryRun(s, `TRUNCATE p`); err == nil {
		t.Fatal("truncate of a referenced table must fail")
	}
	if _, err := tryRun(s, `TRUNCATE p RESTRICT`); err == nil {
		t.Fatal("RESTRICT must fail")
	}
	run(t, s, `TRUNCATE p, c, g`)
	run(t, s, `INSERT INTO p VALUES (1)`)
	run(t, s, `INSERT INTO c (pid) VALUES (1)`)
	run(t, s, `INSERT INTO g (cid) VALUES (3)`)
	r := run(t, s, `TRUNCATE p CASCADE`)
	if !strings.Contains(r.Notice, "c") {
		t.Fatalf("notice %q", r.Notice)
	}
	wantRows(t, s, `SELECT (SELECT count(*) FROM p), (SELECT count(*) FROM c), (SELECT count(*) FROM g)`, "0|0|0")
	// identity: CONTINUE (default) and RESTART
	run(t, s, `INSERT INTO p VALUES (1)`)
	run(t, s, `INSERT INTO c (pid) VALUES (1)`)
	wantRows(t, s, `SELECT id FROM c`, "4")
	run(t, s, `TRUNCATE c, g CONTINUE IDENTITY`)
	run(t, s, `INSERT INTO c (pid) VALUES (1)`)
	wantRows(t, s, `SELECT id FROM c`, "5")
	run(t, s, `TRUNCATE c, g RESTART IDENTITY`)
	run(t, s, `INSERT INTO c (pid) VALUES (1)`)
	wantRows(t, s, `SELECT id FROM c`, "1")
	// OVERRIDING / DEFAULT VALUES
	run(t, s, `CREATE TABLE ia (id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY, v TEXT DEFAULT 'd')`)
	run(t, s, `CREATE TABLE ib (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v TEXT DEFAULT 'd')`)
	if _, err := tryRun(s, `INSERT INTO ia (id, v) VALUES (5, 'x')`); code(err) != "428C9" {
		t.Fatalf("always: %v", err)
	}
	run(t, s, `INSERT INTO ia (id, v) OVERRIDING SYSTEM VALUE VALUES (5, 'x')`)
	run(t, s, `INSERT INTO ib (id, v) OVERRIDING USER VALUE VALUES (50, 'y')`)
	run(t, s, `INSERT INTO ia DEFAULT VALUES`)
	run(t, s, `INSERT INTO ib DEFAULT VALUES`)
	wantRows(t, s, `SELECT id, v FROM ia ORDER BY id`, "1|d", "5|x")
	wantRows(t, s, `SELECT id, v FROM ib ORDER BY id`, "1|y", "2|d")
	// SET/DROP DEFAULT, SET/DROP NOT NULL
	run(t, s, `ALTER TABLE ib ALTER COLUMN v SET DEFAULT 'zz'`)
	run(t, s, `INSERT INTO ib DEFAULT VALUES`)
	run(t, s, `ALTER TABLE ib ALTER COLUMN v SET NOT NULL`)
	if _, err := tryRun(s, `INSERT INTO ib (v) VALUES (NULL)`); code(err) != "23502" {
		t.Fatalf("not null: %v", err)
	}
	run(t, s, `ALTER TABLE ib ALTER COLUMN v DROP NOT NULL`)
	run(t, s, `INSERT INTO ib (v) VALUES (NULL)`)
	run(t, s, `ALTER TABLE ib ALTER COLUMN v DROP DEFAULT`)
	run(t, s, `INSERT INTO ib (id) VALUES (99)`)
	wantRows(t, s, `SELECT id, v FROM ib WHERE id IN (3, 99) ORDER BY id`, "3|zz", "99|NULL")
}

func TestMergeBasic(t *testing.T) {
	e := newEngine(t)
	s := NewSession(e)
	run(t, s, `CREATE TABLE tgt (number TEXT PRIMARY KEY, status TEXT, price NUMERIC(12,2) DEFAULT 1)`)
	run(t, s, `CREATE TABLE stg (number TEXT, status TEXT, price NUMERIC(12,2), del BOOLEAN)`)
	run(t, s, `INSERT INTO tgt VALUES ('1','old',10),('2','old',20),('3','old',30),('4','keep',40)`)
	run(t, s, `INSERT INTO stg VALUES ('1','new',11,false),('2',NULL,0,true),('5','fresh',55,false),('3','same',33,false)`)
	r := run(t, s, `MERGE INTO tgt t USING stg s ON t.number = s.number
		WHEN MATCHED AND s.del THEN DELETE
		WHEN MATCHED AND s.status = 'same' THEN DO NOTHING
		WHEN MATCHED THEN UPDATE SET status = s.status, price = s.price + t.price
		WHEN NOT MATCHED THEN INSERT (number, status, price) VALUES (s.number, s.status, s.price)`)
	if r.Tag != "MERGE 3" {
		t.Fatalf("tag %q", r.Tag)
	}
	wantRows(t, s, `SELECT number, status, price FROM tgt ORDER BY number`,
		"1|new|21.00", "3|old|30.00", "4|keep|40.00", "5|fresh|55.00")
	// a target row hit twice
	run(t, s, `INSERT INTO stg VALUES ('1','dup',1,false)`)
	if _, err := tryRun(s, `MERGE INTO tgt USING stg ON tgt.number = stg.number WHEN MATCHED THEN UPDATE SET status = stg.status`); code(err) != "21000" {
		t.Fatalf("twice: %v", err)
	}
	wantRows(t, s, `SELECT status FROM tgt WHERE number = '1'`, "new") // the failed MERGE changed nothing
	// subquery source, DEFAULT, parameters
	run(t, s, `MERGE INTO tgt USING (SELECT '9' AS n, 'x' AS st) q ON tgt.number = q.n WHEN NOT MATCHED THEN INSERT (number, status, price) VALUES (q.n, q.st, DEFAULT)`)
	wantRows(t, s, `SELECT price FROM tgt WHERE number = '9'`, "1.00")
	r = run(t, s, `MERGE INTO tgt USING (SELECT $1::text AS n) q ON tgt.number = q.n WHEN MATCHED THEN DELETE`, TextD("9"))
	if r.Tag != "MERGE 1" {
		t.Fatalf("param: %q", r.Tag)
	}
	// in a transaction, rolled back
	run(t, s, `BEGIN`)
	run(t, s, `MERGE INTO tgt USING stg ON tgt.number = stg.number AND stg.status = 'fresh' WHEN MATCHED THEN DELETE`)
	run(t, s, `ROLLBACK`)
	wantRows(t, s, `SELECT count(*) FROM tgt WHERE number = '5'`, "1")
	// no PK target
	run(t, s, `CREATE TABLE np (a INTEGER, b TEXT)`)
	run(t, s, `INSERT INTO np VALUES (1,'a'),(2,'b')`)
	run(t, s, `MERGE INTO np USING (VALUES (2,'B'),(3,'c')) v(a,b) ON np.a = v.a WHEN MATCHED THEN UPDATE SET b = v.b WHEN NOT MATCHED THEN INSERT VALUES (v.a, v.b)`)
	wantRows(t, s, `SELECT a, b FROM np ORDER BY a`, "1|a", "2|B", "3|c")
}

// TestMergeModel compares MERGE with a reference model on random data.
func TestMergeModel(t *testing.T) {
	for seed := int64(1); seed <= 25; seed++ {
		rng := rand.New(rand.NewSource(seed))
		e := newEngine(t)
		s := NewSession(e)
		run(t, s, `CREATE TABLE t (k INTEGER PRIMARY KEY, v INTEGER, tag TEXT)`)
		run(t, s, `CREATE TABLE src (k INTEGER, v INTEGER, op TEXT)`)
		model := map[int][2]any{} // k -> v, tag
		for i := 0; i < 30; i++ {
			k := rng.Intn(60)
			if _, ok := model[k]; ok {
				continue
			}
			v := rng.Intn(100)
			model[k] = [2]any{v, "t"}
			run(t, s, fmt.Sprintf(`INSERT INTO t VALUES (%d,%d,'t')`, k, v))
		}
		type srow struct {
			k, v int
			op   string
		}
		var rows []srow
		seen := map[int]bool{}
		for i := 0; i < 40; i++ {
			k := rng.Intn(80)
			if seen[k] {
				continue
			}
			seen[k] = true
			rows = append(rows, srow{k, rng.Intn(100), []string{"u", "d", "n", "i"}[rng.Intn(4)]})
		}
		for _, r := range rows {
			run(t, s, fmt.Sprintf(`INSERT INTO src VALUES (%d,%d,'%s')`, r.k, r.v, r.op))
		}
		// model: matched & op=d -> delete; matched & v even -> update; matched -> nothing for op=n; not matched & op<>'n' -> insert
		want := 0
		for _, r := range rows {
			cur, ok := model[r.k]
			switch {
			case ok && r.op == "d":
				delete(model, r.k)
				want++
			case ok && r.op == "n":
			case ok:
				model[r.k] = [2]any{cur[0].(int) + r.v, "m"}
				want++
			case !ok && r.op != "n":
				model[r.k] = [2]any{r.v, "i"}
				want++
			}
		}
		res := run(t, s, `MERGE INTO t USING src ON t.k = src.k
			WHEN MATCHED AND src.op = 'd' THEN DELETE
			WHEN MATCHED AND src.op = 'n' THEN DO NOTHING
			WHEN MATCHED THEN UPDATE SET v = t.v + src.v, tag = 'm'
			WHEN NOT MATCHED AND src.op <> 'n' THEN INSERT VALUES (src.k, src.v, 'i')`)
		if res.Tag != fmt.Sprintf("MERGE %d", want) {
			t.Fatalf("seed %d: tag %q, want MERGE %d", seed, res.Tag, want)
		}
		var keys []int
		for k := range model {
			keys = append(keys, k)
		}
		sort.Ints(keys)
		var exp []string
		for _, k := range keys {
			exp = append(exp, fmt.Sprintf("%d|%d|%s", k, model[k][0], model[k][1]))
		}
		got := cellsOf(run(t, s, `SELECT k, v, tag FROM t ORDER BY k`))
		if strings.Join(got, ";") != strings.Join(exp, ";") {
			t.Fatalf("seed %d:\n got  %v\n want %v", seed, got, exp)
		}
	}
}
